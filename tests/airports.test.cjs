const assert = require('node:assert/strict');
const {createCatalog, label} = require('../airports.js');
const places = require('../data/airports.json');
const catalog = createCatalog(places);
assert.equal(catalog.resolve('Palermo').code, 'PMO');
assert.equal(catalog.resolve('pmo').code, 'PMO');
assert.equal(catalog.resolve('zzzzzz'), null);
assert.equal(catalog.resolve('Palermoo'), null, 'typos need explicit selection');
assert.equal(catalog.search('Palermoo')[0].code, 'PMO');
assert.equal(catalog.search('Pal')[0].code, 'PAL', 'exact code outranks name prefix');
assert.equal(catalog.search('Palermo')[0].code, 'PMO');
assert.equal(catalog.search('London')[0].code, 'LON');
assert.equal(catalog.resolve('London'), null, 'London also names cities outside the UK');
assert.equal(catalog.resolve('Springfield'), null, 'ambiguous cities require a choice');
assert.equal(catalog.search('lhr')[0].code, 'LHR');
assert.equal(catalog.search('heathrow')[0].code, 'LHR');
assert.equal(catalog.search('sao paulo')[0].type, 'city');
for (const place of places) assert.equal(catalog.resolve(label(place)).code, place.code);
console.log('Airport mapping, ranking, typo and catalog round-trip checks passed');
